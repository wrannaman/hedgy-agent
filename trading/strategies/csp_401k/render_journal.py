#!/usr/bin/env python3
"""Render POSITIONS.md from state/trade_log.json. Nobody hand-edits the markdown.

POSITIONS.md used to be maintained by hand while claiming, in its own header, to
mirror trade_log.json. That is a copy of a fact that already lives somewhere else —
the exact thing `trading/CLAUDE.md`'s DRY rule forbids — and it had all three of the
predictable failure modes: the two files could disagree, the totals row was arithmetic
redone by hand on every close, and the closed-trade table grew without bound because
nothing ever decided what to drop.

So it is generated now. The JSON is the source of truth; this is a view of it.

What can't be derived stays in the JSON where it belongs: each trade's `notes` and
`close_notes` carry the reasoning, such as a timer-based close or an explicit
owner decision. Those annotations are useful audit context, so they are
rendered underneath the table rather than thrown away — but they are stored once, on
the trade, not transcribed into prose here.

Usage:  python3 render_journal.py            # write POSITIONS.md
        python3 render_journal.py --check    # exit 1 if it's stale (for CI/cron)
"""
import json
import sys
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOG_PATH = HERE / "state" / "trade_log.json"
OUT_PATH = HERE / "POSITIONS.md"

# How many closed trades to show in full. The rest collapse into a one-line tail so the
# file stays a readable page instead of an ever-growing ledger — the full history is in
# the JSON, which is the thing that actually has to be complete.
RECENT_CLOSED = 15


def _fmt_date(value):
    """Trade timestamps are ISO strings, sometimes date-only. Render just the date."""
    if not value:
        return "—"
    return str(value)[:10]


def _label(t):
    """'MARA $8 put x9' — strategy and size in one cell."""
    kind = {
        "cash_secured_put": "put",
        "put_spread": "put spread",
        "covered_call": "call",
    }.get(t.get("strategy"), t.get("strategy", "?"))
    strike = t.get("sell_strike")
    strike_s = f"${strike:,.0f}" if strike else ""
    if t.get("buy_strike"):
        strike_s = f"${t['sell_strike']:,.0f}/${t['buy_strike']:,.0f}"
    n = t.get("contracts") or 1
    suffix = f" x{n:g}" if n and n != 1 else ""
    return f"{t['symbol']} {strike_s} {kind}{suffix}".replace("  ", " ").strip()


def _strategy_name(t):
    return {
        "cash_secured_put": "Cash-secured put",
        "put_spread": "Put spread",
        "covered_call": "Covered call",
    }.get(t.get("strategy"), t.get("strategy", "—"))


def _result_cell(t):
    """'WIN (50% of max, 14 days)' — pulled from the exit journal, never recomputed."""
    result = (t.get("result") or "").upper() or "—"
    exit_j = (t.get("journal") or {}).get("exit") or {}
    bits = []
    pct = exit_j.get("pct_of_max")
    if pct is not None:
        bits.append(f"{pct:g}% of max")
    days = exit_j.get("days_held")
    if days is None and t.get("opened") and t.get("closed"):
        try:
            days = (datetime.fromisoformat(str(t["closed"])).date()
                    - datetime.fromisoformat(str(t["opened"])).date()).days
        except ValueError:
            days = None
    if days is not None:
        bits.append(f"{days} days")
    return f"{result} ({', '.join(bits)})" if bits else result


def _money(v):
    if v is None:
        return "—"
    return f"{v:+,.0f}" if v < 0 else f"+${v:,.0f}"


def render(log):
    trades = log.get("trades", [])
    open_t = [t for t in trades if t.get("status") == "open"]
    closed = [t for t in trades if t.get("status") == "closed"]
    closed.sort(key=lambda t: str(t.get("closed") or ""))

    L = []
    L.append("<!-- GENERATED by render_journal.py from state/trade_log.json — do not edit by hand. -->")
    L.append("<!-- Add reasoning to a trade's notes/close_notes in the JSON; it renders below. -->")
    L.append("")
    L.append("# csp_401k — Trade Journal")
    L.append("")
    L.append("Human-readable view of the **csp_401k** put-selling book. **Not a holdings snapshot.**")
    L.append("")
    L.append("**Source of truth**")
    L.append("- Open positions + closed trades: `state/trade_log.json`. This file is generated from it.")
    L.append("- 401k cash, equities, account balance: the latest `401k-Positions-*.csv` in")
    L.append("  `../../positions/`, or live via `monitor.py` / `daily_scan.py`. Those drift every")
    L.append("  day — they are never copied into this file.")
    L.append("")

    L.append("## Open Option Positions")
    L.append("")
    if open_t:
        L.append("| # | Position | Strategy | Opened | Credit | Expires | Notes |")
        L.append("|---|----------|----------|--------|--------|---------|-------|")
        for t in open_t:
            L.append(f"| {t['id']} | {_label(t)} | {_strategy_name(t)} | {_fmt_date(t.get('opened'))} "
                     f"| ${t.get('credit', 0):,.0f} | {t.get('expiration', '—')} "
                     f"| {(t.get('notes') or '').strip()} |")
    else:
        L.append("None.")
    L.append("")

    L.append("## Closed Trades")
    L.append("")
    shown = closed[-RECENT_CLOSED:]
    hidden = len(closed) - len(shown)
    if hidden > 0:
        L.append(f"Most recent {len(shown)} of {len(closed)}. "
                 f"The other {hidden} are in `state/trade_log.json`.")
        L.append("")
    if shown:
        L.append("| # | Position | Strategy | Opened | Closed | Credit | P&L | Result |")
        L.append("|---|----------|----------|--------|--------|--------|-----|--------|")
        for t in shown:
            L.append(f"| {t['id']} | {_label(t)} | {_strategy_name(t)} | {_fmt_date(t.get('opened'))} "
                     f"| {_fmt_date(t.get('closed'))} | ${t.get('credit', 0):,.0f} "
                     f"| {_money(t.get('pnl'))} | {_result_cell(t)} |")
    else:
        L.append("None yet.")
    L.append("")

    # The reasoning, stored once per trade in the JSON, surfaced here.
    notes = [(t, (t.get("close_notes") or "").strip()) for t in shown]
    notes = [(t, n) for t, n in notes if n]
    if notes:
        L.append("### Why each closed")
        L.append("")
        for t, n in notes:
            L.append(f"- **#{t['id']} {t['symbol']}** — {n}")
        L.append("")

    wins = [t for t in closed if t.get("result") == "win"]
    pnl = sum(t.get("pnl") or 0 for t in closed)
    credit = sum(t.get("credit") or 0 for t in closed)
    streak = 0
    for t in reversed(closed):
        if t.get("result") == "loss":
            streak += 1
        else:
            break

    L.append("## Performance")
    L.append("")
    L.append("Closed-trade totals — fixed history, not live account state.")
    L.append("")
    if closed:
        L.append(f"- Closed trades: {len(closed)} — win rate {len(wins)}/{len(closed)} "
                 f"({len(wins) / len(closed) * 100:.0f}%)")
    else:
        L.append("- Closed trades: 0")
    L.append(f"- Premium collected: ${credit:,.0f} · Realized P&L: {_money(pnl)}")
    L.append(f"- Consecutive losses: {streak}")
    L.append("")
    L.append("## Rules")
    L.append("")
    L.append("The rules do not live here. There is one canonical rule set for this strategy:")
    L.append("- **[`RULES.md`](RULES.md)** — the rules + reasoning + citations (for humans)")
    L.append("- **[`rules.py`](rules.py)** — the same thresholds as numbers (imported by all code)")
    L.append("")
    L.append("This file is the trade **journal** only. It states no rules of its own.")
    return "\n".join(L) + "\n"


def main(argv):
    with open(LOG_PATH) as f:
        content = render(json.load(f))

    if "--check" in argv:
        current = OUT_PATH.read_text() if OUT_PATH.exists() else ""
        if current != content:
            print(f"STALE: {OUT_PATH.name} does not match trade_log.json — run render_journal.py")
            return 1
        print(f"{OUT_PATH.name} is up to date.")
        return 0

    OUT_PATH.write_text(content)
    print(f"Wrote {OUT_PATH} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
